      // Με το νέο ημερολόγιο ο Ευαγγελισμός δεν συμπίπτει ποτέ με τη Μεγάλη Εβδομάδα.
      if (key === '03-25') return R('fish', 'Ευαγγελισμός της Θεοτόκου');
      if (off === -3) return R('oil', 'Μεγάλη Πέμπτη', 'Κατάλυση οίνου και ελαίου για τη μνήμη του Μυστικού Δείπνου.');
      if (off >= -6) return R('dry', 'Μεγάλη Εβδομάδα');
      if (off === -7) return R('fish', 'Κυριακή των Βαΐων');
      if (off === -8) return R('oil', 'Σάββατο του Λαζάρου', 'Κατά την παράδοση επιτρέπεται και το αυγοτάραχο.');
      if (weekend) return R('oil', 'Μεγάλη Τεσσαρακοστή');
