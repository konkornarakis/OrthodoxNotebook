    if (key === '01-05') return weekend ? R('oil', 'Παραμονή των Θεοφανείων', 'Πέφτει Σάββατο ή Κυριακή· επιτρέπεται το λάδι.') : R('dry', 'Παραμονή των Θεοφανείων');
