    if (off === -2) return HYMNS.goodFriday;
    if (off >= -6 && off <= -1) return HYMNS.holyWeek;
    if (key === '03-25') return HYMNS.annunciation;
    if (off >= -48 && off < -7) return HYMNS.lent;
    if (off >= -70 && off < -48) return HYMNS.triodion;
    if (off >= 0 && off <= 38) return HYMNS.pascha;
    if (off >= 39 && off <= 47) return HYMNS.ascension;
    if (off >= 48 && off <= 56) return HYMNS.pentecost;
    if (key === '06-29' || (date >= addDays(easter(y), 57) && date <= new Date(y, 5, 28))) return HYMNS.apostles;
    if (key === '08-06') return HYMNS.transfig;
    if (m === 8 && d <= 23) return HYMNS.dormition;
    if (key === '09-14') return HYMNS.cross;
    if ((m === 11 && d >= 21) || (m === 12 && d <= 24)) return HYMNS.nativityFast;
    if ((m === 12 && d >= 25) || (m === 1 && d <= 1)) return HYMNS.nativity;
    if (m === 1 && d >= 5 && d <= 14) return HYMNS.theophany;
    if (dow === 0) return HYMNS.sunday;
    if (dow === 3 || dow === 5) return HYMNS.crossDays;
    return HYMNS.prayer;
